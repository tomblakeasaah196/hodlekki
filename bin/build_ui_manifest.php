<?php
// /bin/build_ui_manifest.php
/**
 * Writes includes/ui/asset_manifest.php: a content hash for every file the
 * shell links to, so each URL carries ?v=<hash> and assets/ui/.htaccess can
 * let phones cache them for a year. A deploy that changes a byte changes the
 * URL; nothing else ever needs a cache-busting bump.
 *
 *   php bin/build_ui_manifest.php <output.php> <fresh app.css> <fresh icons.svg>
 *
 * Called by bin/build_ui.sh. Text files are hashed with LF line endings so a
 * Windows checkout (CRLF) and CI produce the same manifest.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit;
}

[$self, $out, $freshCss, $freshSprite] = array_pad($argv, 4, '');
if ($out === '' || !is_file($freshCss) || !is_file($freshSprite)) {
    fwrite(STDERR, "usage: php bin/build_ui_manifest.php <output.php> <app.css> <icons.svg>\n");
    exit(2);
}

$root = dirname(__DIR__);

function ui_manifest_hash(string $path): string
{
    $bytes = (string) file_get_contents($path);
    // .mjs too: the vendored qrcode module is an ES module, and a Windows
    // checkout gives it CRLF like any other text file.
    if (preg_match('/\.(css|js|mjs|svg|json|txt)$/', $path)) {
        $bytes = str_replace("\r\n", "\n", $bytes);
    }

    return substr(hash('sha256', $bytes), 0, 12);
}

$entries = [
    '/assets/ui/app.css' => ui_manifest_hash($freshCss),
    '/assets/ui/icons.svg' => ui_manifest_hash($freshSprite),
];

$globs = [
    '/assets/ui/js/*.js',
    '/assets/ui/js/pages/*.js',
    '/assets/ui/vendor/*.js',
    '/assets/ui/vendor/*/*.js',
    '/assets/ui/vendor/*/*.css',
    '/assets/ui/vendor/*/*.mjs',
];
$singles = [
    '/assets/js/global-search.js',
    '/assets/js/modal-manager.js',
    '/assets/js/tab-deeplink.js',
    '/assets/js/monitor_wall.js',      // System Health's live wall (modules/monitor/wall.php)
    '/assets/css/monitor_wall.css',
];

$files = [];
foreach ($globs as $glob) {
    foreach (glob($root . $glob) ?: [] as $file) {
        $files[] = substr($file, strlen($root));
    }
}
foreach ($singles as $single) {
    if (is_file($root . $single)) {
        $files[] = $single;
    }
}
$files = array_unique(str_replace('\\', '/', $files));
sort($files, SORT_STRING);
foreach ($files as $file) {
    $entries[$file] = ui_manifest_hash($root . $file);
}
ksort($entries, SORT_STRING);

$php = "<?php\n"
    . "// /includes/ui/asset_manifest.php\n"
    . "// GENERATED by bin/build_ui.sh — do not edit. Content hashes for ui_asset().\n"
    . "return [\n";
foreach ($entries as $path => $hash) {
    $php .= '    ' . var_export($path, true) . ' => ' . var_export($hash, true) . ",\n";
}
$php .= "];\n";

if (file_put_contents($out, $php) === false) {
    fwrite(STDERR, "cannot write $out\n");
    exit(1);
}
