<?php
// /bin/build_hymnal_search.php
//
// Writes includes/hymnal/search_index.php: the lyrics of the generated hymns,
// already folded for search (see includes/hymnal/search.php for what folding is
// and why there is exactly one implementation of it).
//
// It reads the COMMITTED corpus shards, so it needs no source data and no
// network. Run it after anything that changes includes/hymnal/corpus/ (a corpus
// rebuild, a withdrawn hymn) or hymnal_search_fold():
//
//     php bin/build_hymnal_search.php          write the index
//     php bin/build_hymnal_search.php --check  exit 1 if the committed one is stale
//
// The index records a fingerprint of MANIFEST. If it ever goes stale the site
// ignores it and rebuilds in memory — slower, never wrong — and
// tests/hymnal/search_test.php fails until this script has been run again.

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("CLI only.\n");
}

require_once __DIR__ . '/../includes/hymnal/corpus.php';
require_once __DIR__ . '/../includes/hymnal/search.php';

/** A PHP string literal for text that is already folded to [a-z0-9 ]. */
function hbs_str(string $s): string
{
    return "'" . $s . "'";
}

function hbs_export(array $idx): string
{
    $o = "<?php\n";
    $o .= "// /includes/hymnal/search_index.php\n";
    $o .= "//\n";
    $o .= "// GENERATED by bin/build_hymnal_search.php. Do not edit by hand and do not\n";
    $o .= "// re-sort it: the lyrics of the generated hymns, folded for search. It is\n";
    $o .= "// pinned to corpus/MANIFEST; when the corpus changes, run the script again.\n";
    $o .= "\n";
    $o .= "return [\n";
    $o .= "    'version' => " . (int) $idx['version'] . ",\n";
    $o .= "    'manifest' => " . hbs_str((string) $idx['manifest']) . ",\n";
    $o .= "    'docs' => [\n";
    foreach ($idx['docs'] as $n => $d) {
        $lines = implode(',', array_map('hbs_str', $d['l']));
        $o .= '        ' . (int) $n . " => ['t' => " . hbs_str($d['t']) . ", 'f' => " . hbs_str($d['f'])
            . ", 'w' => " . hbs_str($d['w']) . ", 'h' => " . hbs_str($d['h']) . ", 'l' => [" . $lines . "]],\n";
    }
    $o .= "    ],\n";
    $o .= "    'vocab' => [\n";
    foreach ($idx['vocab'] as $w => $c) {
        $key = ctype_digit((string) $w) && (string) (int) $w === (string) $w ? (string) $w : hbs_str((string) $w);
        $o .= '        ' . $key . ' => ' . (int) $c . ",\n";
    }
    $o .= "    ],\n";
    $o .= "];\n";

    return $o;
}

$idx = hymnal_search_build_corpus();
if ($idx['manifest'] === '') {
    fwrite(STDERR, "corpus/MANIFEST is missing; nothing to index.\n");
    exit(1);
}
$text = hbs_export($idx);

if (in_array('--check', $argv, true)) {
    $have = is_file(HYMNAL_SEARCH_INDEX_FILE) ? str_replace("\r\n", "\n", (string) file_get_contents(HYMNAL_SEARCH_INDEX_FILE)) : '';
    if ($have !== $text) {
        fwrite(STDERR, "search_index.php is stale. Run: php bin/build_hymnal_search.php\n");
        exit(1);
    }
    echo "search_index.php is current (" . count($idx['docs']) . " hymns, " . count($idx['vocab']) . " words).\n";
    exit(0);
}

file_put_contents(HYMNAL_SEARCH_INDEX_FILE, $text);
printf("Wrote %s: %d hymns, %d words, %d KB.\n", basename(HYMNAL_SEARCH_INDEX_FILE), count($idx['docs']), count($idx['vocab']), (int) (strlen($text) / 1024));
