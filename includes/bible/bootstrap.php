const BIBLE_TABLES = [
    'bible_user_state', 'bible_highlights', 'bible_notes', 'bible_note_refs', 'bible_tags',
    'bible_note_tags', 'bible_chapter_cache', 'bible_api_usage', 'bible_config',
    'bible_reading_log', 'bible_plan_enrollments', 'bible_plan_progress',
];

function bible_env(string $name, string $default = ''): string
{
    $v = $_ENV[$name] ?? getenv($name);

    return is_string($v) && trim($v) !== '' ? trim($v) : $default;
}

/**
 * Does $table exist? Cached per request. Works on MySQL/MariaDB and on the
 * SQLite database the tests use.
 */
function bible_table_exists(PDO $pdo, string $table): bool
{
    static $cache = [];
    $key = spl_object_id($pdo) . ':' . $table;
    if (array_key_exists($key, $cache)) {
        return $cache[$key];
    }

    try {
        if ($pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'sqlite') {
            $stmt = $pdo->prepare("SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = ?");
            $stmt->execute([$table]);
        } else {
            $stmt = $pdo->prepare('SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name = ?');
            $stmt->execute([$table]);
        }
        $cache[$key] = (int) $stmt->fetchColumn() > 0;
    } catch (Throwable $e) {
        error_log('Bible table check: ' . $e->getMessage());
        $cache[$key] = false;
    }

    return $cache[$key];
}

/** Has the bible_core migration run? */
function bible_ready(?PDO $pdo): bool
{
    if ($pdo === null) {
        return false;
    }
    foreach (BIBLE_TABLES as $t) {
        if (!bible_table_exists($pdo, $t)) {
            return false;
        }
    }

    return true;
}

/**
 * Everything the reader needs on first paint. modules/bible/index.php prints
 * it into the page; api/bible_api.php?action=boot returns the same thing.
 */
function bible_boot_payload(PDO $pdo, int $userId): array
{
    $ready = bible_ready($pdo);
    $plans = [];
    $streak = null;
    if ($ready) {
        try {
            foreach (bible_enrollments($pdo, $userId, 'active') as $en) {
                $plans[] = bible_plan_overview($pdo, $userId, $en);
            }
            $streak = bible_streak($pdo, $userId);
        } catch (Throwable $e) {
            error_log('Bible boot: ' . $e->getMessage());
        }
    }

    return [
        'ready'        => $ready,
        'translations' => bible_translations($pdo),
        'state'        => bible_state_get($pdo, $userId),
        'plans'        => $plans,
        'streak'       => $streak,
        'books'        => array_values(array_map(static fn(array $b): array => [
            'id'        => $b['id'],
            'name'      => $b['name'],
            'short'     => $b['short'],
            'chapters'  => $b['chapters'],
            'group'     => $b['group'],
            'testament' => $b['testament'],
        ], bible_books())),
        'counts'       => bible_kjv_counts(),
        'colors'       => BIBLE_HL_COLORS,
        'is_admin'     => function_exists('security_is_admin') && security_is_admin($pdo, $userId),
        'today'        => bible_today(),
    ];
}

/**
 * A chapter with the member's highlights and notes on it, as the reader
 * renders it.
 *
 * @return array{ok:bool, code?:string, message?:string, data?:array}
 */
function bible_chapter_for_user(PDO $pdo, int $userId, string $translation, int $book, int $chapter): array
{
    $res = bible_chapter($pdo, $translation, $book, $chapter);
    if (!$res['ok']) {
        return $res;
    }
    $data = $res['data'];
    $data['highlights'] = [];
    $data['notes'] = [];
    $data['read_today'] = false;
    if (bible_ready($pdo)) {
        $data['highlights'] = bible_highlights_for_chapter($pdo, $userId, $data['translation'], $book, $chapter);
        $data['notes'] = bible_notes_for_chapter($pdo, $userId, $book, $chapter);
        $stmt = $pdo->prepare('SELECT 1 FROM bible_reading_log WHERE user_id = ? AND book = ? AND chapter = ? AND read_on = ? LIMIT 1');
        $stmt->execute([$userId, $book, $chapter, bible_today()]);
        $data['read_today'] = $stmt->fetchColumn() !== false;
    }

    return ['ok' => true, 'data' => $data];
}

/** Lagos time, as everywhere else on the platform (includes/db.php). */
function bible_now(): string
{
    return date('Y-m-d H:i:s');
}

function bible_today(): string
{
    return date('Y-m-d');
}

function bible_month(): string
{
    return date('Y-m');
}
