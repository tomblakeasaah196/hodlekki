/**
 * The chapters either side of (book, chapter), crossing book boundaries.
 *
 * @return array{prev: ?array{book:int, chapter:int, ref:string}, next: ?array{book:int, chapter:int, ref:string}}
 */
function bible_neighbours(int $book, int $chapter): array
{
    $prev = null;
    $next = null;

    if ($chapter > 1) {
        $prev = [$book, $chapter - 1];
    } elseif ($book > 1) {
        $prev = [$book - 1, bible_book($book - 1)['chapters']];
    }

    $meta = bible_book($book);
    if ($meta !== null && $chapter < $meta['chapters']) {
        $next = [$book, $chapter + 1];
    } elseif ($book < 66) {
        $next = [$book + 1, 1];
    }

    $shape = static fn(?array $p): ?array => $p === null ? null : [
        'book'    => $p[0],
        'chapter' => $p[1],
        'ref'     => bible_format_ref($p[0], $p[1]),
    ];

    return ['prev' => $shape($prev), 'next' => $shape($next)];
}

/**
 * Load one chapter in one translation.
 *
 * @return array{ok:bool, code?:string, message?:string, data?:array}
 */
function bible_chapter(?PDO $pdo, string $translation, int $book, int $chapter): array
{
    $translation = bible_translation_code($translation);
    if (!bible_chapter_exists($book, $chapter)) {
        return ['ok' => false, 'code' => 'NOT_FOUND', 'message' => 'That chapter is not in the Bible.'];
    }

    $copyright = BIBLE_TRANSLATIONS[$translation]['copyright'];
    $fums      = null;
    $source    = 'local';

    if (bible_is_local($translation)) {
        $verses = bible_kjv_chapter($book, $chapter);
        if ($verses === null || $verses === []) {
            return ['ok' => false, 'code' => 'NOT_FOUND', 'message' => 'That chapter could not be loaded.'];
        }
    } else {
        $res = bible_api_chapter($pdo, $translation, $book, $chapter);
        if (!$res['ok']) {
            return $res;
        }
        $verses    = $res['verses'];
        $copyright = $res['copyright'] !== '' ? $res['copyright'] : $copyright;
        $fums      = $res['fums_token'];
        $source    = $res['source'];
    }

    $meta = bible_book($book);

    return ['ok' => true, 'data' => [
        'translation' => $translation,
        'book'        => $book,
        'chapter'     => $chapter,
        'book_name'   => $meta['name'],
        'chapters'    => $meta['chapters'],
        'ref'         => bible_format_ref($book, $chapter),
        'verses'      => $verses,
        'copyright'   => $copyright,
        'fums_token'  => $fums,
        'source'      => $source,
        // The KJV prints LORD and other all-capital words in small capitals.
        'caps_sc'     => $translation === 'KJV',
    ] + bible_neighbours($book, $chapter)];
}

/**
 * Verse number → text for a chapter, or [] when it cannot be loaded without
 * spending an API call (used to validate highlight offsets and cut quotes).
 *
 * @return array<int, string>
 */
function bible_chapter_texts(?PDO $pdo, string $translation, int $book, int $chapter): array
{
    if (bible_is_local($translation)) {
        $verses = bible_kjv_chapter($book, $chapter) ?? [];
    } else {
        $verses = bible_api_cached_verses($pdo, $translation, $book, $chapter) ?? [];
    }

    $out = [];
    foreach ($verses as $v) {
        $out[(int) $v['v']] = (string) $v['t'];
    }

    return $out;
}

/**
 * The words between two positions of a chapter, joined with spaces.
 *
 * @param array<int, string> $texts verse => text
 */
function bible_cut_quote(array $texts, int $vs, int $os, int $ve, int $oe): string
{
    $parts = [];
    for ($v = $vs; $v <= $ve; $v++) {
        if (!isset($texts[$v])) {
            continue;
        }
        $t     = $texts[$v];
        $start = $v === $vs ? $os : 0;
        $end   = $v === $ve ? $oe : mb_strlen($t, 'UTF-8');
        if ($end > $start) {
            $parts[] = mb_substr($t, $start, $end - $start, 'UTF-8');
        }
    }

    return trim(preg_replace('/\s+/u', ' ', implode(' ', $parts)) ?? '');
}

