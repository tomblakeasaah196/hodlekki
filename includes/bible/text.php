/**
 * Split a query into terms: "quoted phrases" stay whole, other words are
 * matched at the start of a word, so "love" also finds "loved" and "loveth".
 *
 * @return list<string>
 */
function bible_search_terms(string $query): array
{
    $query = trim(preg_replace('/\s+/u', ' ', $query) ?? '');
    $terms = [];
    if (preg_match_all('/"([^"]+)"|(\S+)/u', $query, $m, PREG_SET_ORDER)) {
        foreach ($m as $hit) {
            $term = trim($hit[1] !== '' ? $hit[1] : ($hit[2] ?? ''));
            $term = trim($term, " \t,.;:!?'\"()");
            if (mb_strlen($term, 'UTF-8') >= 2) {
                $terms[] = mb_strtolower($term, 'UTF-8');
            }
        }
    }

    return array_slice(array_values(array_unique($terms)), 0, 8);
}

/**
 * Scope → [first book, last book].
 *
 * @return array{0:int, 1:int}
 */
function bible_search_scope(string $scope): array
{
    if ($scope === 'ot') {
        return [1, 39];
    }
    if ($scope === 'nt') {
        return [40, 66];
    }
    if (preg_match('/^book:(\d{1,2})$/', $scope, $m) && bible_book((int) $m[1]) !== null) {
        return [(int) $m[1], (int) $m[1]];
    }

    return [1, 66];
}

/**
 * Full-text search over the KJV, in canonical order. Every term must occur.
 *
 * @return array{total:int, results:list<array{book:int, chapter:int, verse:int, ref:string, text:string}>, terms:list<string>, by_book: array<int,int>}
 */
function bible_kjv_search(string $query, string $scope = 'all', int $limit = 30, int $offset = 0): array
{
    $terms = bible_search_terms($query);
    if ($terms === []) {
        return ['total' => 0, 'results' => [], 'terms' => [], 'by_book' => []];
    }

    $patterns = [];
    foreach ($terms as $term) {
        $words = array_map(static fn(string $w): string => preg_quote($w, '/'), explode(' ', $term));
        $patterns[] = '/(?<![\p{L}])' . implode('\s+', $words) . '/iu';
    }

    [$from, $to] = bible_search_scope($scope);
    $total   = 0;
    $results = [];
    $byBook  = [];

    for ($b = $from; $b <= $to; $b++) {
        foreach (bible_kjv_book($b) as $c => $rows) {
            foreach ($rows as $row) {
                $text = $row[1];
                foreach ($patterns as $p) {
                    if (!preg_match($p, $text)) {
                        continue 2;
                    }
                }
                $total++;
                $byBook[$b] = ($byBook[$b] ?? 0) + 1;
                if ($total > $offset && count($results) < $limit) {
                    $results[] = [
                        'book'    => $b,
                        'chapter' => (int) $c,
                        'verse'   => (int) $row[0],
                        'ref'     => bible_format_ref($b, (int) $c, (int) $row[0]),
                        'text'    => $text,
                    ];
                }
            }
        }
    }

    return ['total' => $total, 'results' => $results, 'terms' => $terms, 'by_book' => $byBook];
}
