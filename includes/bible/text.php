/**
 * One KJV book as generated by bin/build_bible_kjv.php.
 *
 * @return array<int, list<array>>
 */
function bible_kjv_book(int $book): array
{
    static $cache = [];
    if (!isset($cache[$book])) {
        $file = sprintf('%s/kjv/%02d.php', __DIR__, $book);
        $cache[$book] = is_file($file) ? (require $file) : [];
    }

    return $cache[$book];
}

/**
 * Verses per chapter, [book => [chapter => count]].
 *
 * @return array<int, array<int, int>>
 */
function bible_kjv_counts(): array
{
    static $counts = null;
    if ($counts === null) {
        $counts = require __DIR__ . '/kjv/counts.php';
    }

    return $counts;
}

/**
 * Expand a stored [n, text, extras] row into the shared verse shape.
 */
function bible_kjv_verse(array $row): array
{
    $verse = ['v' => (int) $row[0], 't' => (string) $row[1]];
    foreach (($row[2] ?? []) as $k => $v) {
        $verse[$k] = $v;
    }

    return $verse;
}

/**
 * @return list<array>|null
 */
function bible_kjv_chapter(int $book, int $chapter): ?array
{
    $rows = bible_kjv_book($book)[$chapter] ?? null;
    if ($rows === null) {
        return null;
    }

    return array_map('bible_kjv_verse', $rows);
}

