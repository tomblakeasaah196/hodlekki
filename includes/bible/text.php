// Scripture text: which translations exist, loading a chapter, and search.
//
// A chapter is always returned in one shape, whatever its source, so the
// reader, the voice reader and the highlighter never care where it came from:
//
//   ['v' => 16, 't' => 'For God so loved …', 'p' => 1, 'q' => 1,
//    'd' => 'A Psalm of David.', 'h' => ['The New Birth'],
//    'w' => [s, e, …], 'i' => [s, e, …], 'n' => [s, e, …], 'br' => [o, …]]
//
// t is the verse text; offsets count characters (code points) into it.
// p opens a paragraph, q is a line of poetry, d is a title printed above the
// verse, h are section headings above it (licensed translations only), w is
// words of Jesus, i supplied words (italics), n small capitals (LORD), and br
// line breaks inside the verse.

const BIBLE_TRANSLATIONS = [
    'KJV' => [
        'code'      => 'KJV',
        'name'      => 'King James Version',
        'source'    => 'local',
        'copyright' => 'King James Version (1769 standard text). Public domain.',
    ],
    'NKJV' => [
        'code'      => 'NKJV',
        'name'      => 'New King James Version',
        'source'    => 'api',
        'copyright' => 'Scripture taken from the New King James Version®. Copyright © 1982 by Thomas Nelson. Used by permission. All rights reserved.',
    ],
    'NIV' => [
        'code'      => 'NIV',
        'name'      => 'New International Version',
        'source'    => 'api',
        'copyright' => 'Scripture quotations taken from The Holy Bible, New International Version® NIV®. Copyright © 1973, 1978, 1984, 2011 by Biblica, Inc.™ Used by permission. All rights reserved worldwide.',
    ],
    'AMP' => [
        'code'      => 'AMP',
        'name'      => 'Amplified Bible',
        'source'    => 'api',
        'copyright' => 'Scripture quotations taken from the Amplified® Bible (AMP), Copyright © 2015 by The Lockman Foundation. Used by permission. www.lockman.org',
    ],
];

/**
 * Normalise a translation code from a request; unknown codes become KJV.
 */
function bible_translation_code(?string $raw): string
{
    $code = strtoupper(preg_replace('/[^A-Za-z]/', '', (string) $raw) ?? '');

    return isset(BIBLE_TRANSLATIONS[$code]) ? $code : 'KJV';
}

function bible_is_local(string $code): bool
{
    return (BIBLE_TRANSLATIONS[$code]['source'] ?? '') === 'local';
}

/**
 * Every translation with whether a member can read it right now.
 *
 * @return list<array{code:string, name:string, source:string, available:bool, reason:string, copyright:string}>
 */
function bible_translations(?PDO $pdo): array
{
    $out = [];
    foreach (BIBLE_TRANSLATIONS as $code => $t) {
        $row = $t + ['available' => true, 'reason' => ''];
        if ($t['source'] === 'api') {
            $status = bible_api_translation_status($pdo, $code);
            $row['available'] = $status['available'];
            $row['reason']    = $status['reason'];
            if ($status['copyright'] !== '') {
                $row['copyright'] = $status['copyright'];
            }
        }
        $out[] = $row;
    }

    return $out;
}

