<?php
// /includes/hymnal/corpus.php
//
// The generated hymns: 511 public-domain hymns read straight from
// includes/hymnal/corpus/, with no database involved at any point.
//
// Why files. Three reasons, in order of weight:
//   1. The tree reaches production before db/migrate.php runs, so a member
//      must be able to read a hymn when no table exists yet.
//   2. The words of a hymn should not be editable by anything, including us.
//      MANIFEST pins a SHA-256 per file and tests/hymnal/run.php fails on any
//      difference, so a hymn cannot drift and a hand edit cannot hide.
//   3. It is how the Bible module already holds the KJV, so there is one
//      pattern on this platform for "text we did not write and must not change".
//
// Nothing here writes. The corpus is regenerated by bin/build_hymnal.php on a
// developer's machine and committed.

/** Hymns per shard file, matching bin/build_hymnal.php. */
const HYMNAL_SHARD_SIZE = 50;

/** The highest HOD number the generated corpus may use (see the migration). */
const HYMNAL_CORPUS_CEILING = 1999;

function hymnal_corpus_dir(): string
{
    return __DIR__ . '/corpus';
}

/**
 * The light index: one row per hymn, enough to browse, search and jump to a
 * number without opening a shard. Loaded once per request.
 *
 * @return list<array>
 */
function hymnal_corpus_index(): array
{
    static $index = null;
    if ($index !== null) {
        return $index;
    }
    $path = hymnal_corpus_dir() . '/index.php';
    $index = is_file($path) ? (array) require $path : [];

    return $index;
}

/** What the corpus is and what it deliberately leaves out. */
function hymnal_corpus_meta(): array
{
    static $meta = null;
    if ($meta !== null) {
        return $meta;
    }
    $path = hymnal_corpus_dir() . '/meta.php';
    $meta = is_file($path) ? (array) require $path : [];

    return $meta;
}

/** HOD number => index row, built once. */
function hymnal_corpus_by_number(): array
{
    static $byNumber = null;
    if ($byNumber !== null) {
        return $byNumber;
    }
    $byNumber = [];
    foreach (hymnal_corpus_index() as $row) {
        $byNumber[(int) $row['n']] = $row;
    }

    return $byNumber;
}

/** Is this HOD number one of the generated hymns? */
function hymnal_corpus_has(int $number): bool
{
    return isset(hymnal_corpus_by_number()[$number]);
}

/**
 * One hymn in full, loading only the shard it lives in.
 *
 * Shards are required, not parsed, so the opcode cache holds them after the
 * first request and a second reader pays nothing.
 */
function hymnal_corpus_song(int $number): ?array
{
    static $shards = [];
    $row = hymnal_corpus_by_number()[$number] ?? null;
    if ($row === null) {
        return null;
    }
    $shard = (int) $row['shard'];
    if (!isset($shards[$shard])) {
        $path = sprintf('%s/%03d.php', hymnal_corpus_dir(), $shard);
        $shards[$shard] = is_file($path) ? (array) require $path : [];
    }
    $song = $shards[$shard][$number] ?? null;

    return $song === null ? null : hymnal_corpus_shape($song);
}

/**
 * A generated hymn in the one shape the reader understands, so nothing above
 * this line cares whether a song came from a file or from the Studio.
 */
function hymnal_corpus_shape(array $s): array
{
    $voices = [];
    foreach ($s['voices'] ?? [] as $v) {
        $voices[] = [
            'id'    => (string) $v['id'],
            'name'  => (string) $v['name'],
            'clef'  => (string) ($v['clef'] ?? ''),
            'doh'   => (string) ($v['doh'] ?? ''),
            'solfa' => $v['solfa'] ?? [],
        ];
    }
    $hasScore = !empty($s['score']['abc']);

    return [
        'n'           => (int) $s['n'],
        'origin'      => 'corpus',
        'title'       => (string) $s['title'],
        'first_line'  => (string) ($s['first_line'] ?? ''),
        'writer'      => (string) ($s['writer'] ?? ''),
        'attribution' => (string) ($s['attribution'] ?? ''),
        'composer'    => '',
        'arranger'    => '',
        'tune'        => '',
        'year'        => $s['year'] ?? null,
        'key'         => (string) ($s['key'] ?? ''),
        'time'        => (string) ($s['time'] ?? ''),
        'bpm'         => $s['bpm'] ?? null,
        'metre'       => (string) ($s['metre'] ?? ''),
        'themes'      => $s['themes'] ?? [],
        'collections' => $s['collections'] ?? [],
        'scripture'   => $s['scripture'] ?? [],
        'licence'     => hymnal_corpus_licence($s['rights'] ?? []),
        'source'      => $s['source'] ?? [],
        'langs'       => [
            'en' => [
                'lang'       => 'en',
                'label'      => 'English',
                'title'      => (string) $s['title'],
                'sections'   => $s['sections'] ?? [],
                'sing_order' => $s['sing_order'] ?? [],
                'chordpro'   => (string) ($s['chordpro'] ?? ''),
            ],
        ],
        'score'       => $hasScore
            ? ['abc' => (string) $s['score']['abc'], 'doh' => (string) ($s['score']['doh'] ?? ''), 'voices' => $voices]
            : null,
        'no_score'    => $hasScore ? '' : (string) ($s['no_score'] ?? ''),
        'has'         => [
            'score'  => $hasScore,
            'solfa'  => $hasScore && $voices !== [],
            'chords' => trim((string) ($s['chordpro'] ?? '')) !== '',
            // Playback is synthesised from the score, so it is available for
            // exactly the hymns that have one. Nothing is recorded per hymn.
            'audio'  => $hasScore,
        ],
    ];
}

/**
 * The licence line a member sees, built from the per-part record the corpus
 * build verified. Spelled out part by part because that is the honest answer:
 * the words, the tune and the harmony each have their own status.
 */
function hymnal_corpus_licence(array $rights): array
{
    $parts = [];
    foreach (['text' => 'Words', 'tune' => 'Tune', 'arrangement' => 'Harmony'] as $k => $label) {
        if (!isset($rights[$k])) {
            continue;
        }
        $parts[] = [
            'part'    => $label,
            'licence' => (string) ($rights[$k]['license'] ?? ''),
            'basis'   => (string) ($rights[$k]['basis'] ?? ''),
        ];
    }

    return [
        'code'   => 'PD',
        'label'  => 'Public domain',
        'detail' => 'Words, tune and harmony are each in the public domain.',
        'parts'  => $parts,
    ];
}

/**
 * Search the generated hymns.
 *
 * Small enough (511 rows) to scan in PHP, which keeps search working before the
 * migration has run and means one code path serves both halves of the library.
 *
 * A bare number is treated as a hymn number first, because that is what someone
 * types when the Pastor calls one out.
 *
 * @return list<array> index rows, best first
 */
function hymnal_corpus_search(string $query, array $opts = []): array
{
    $q = trim(preg_replace('/\s+/u', ' ', $query) ?? '');
    $collection = (string) ($opts['collection'] ?? '');
    $scoreOnly  = !empty($opts['score_only']);

    $rows = hymnal_corpus_index();
    if ($collection !== '') {
        $rows = array_values(array_filter(
            $rows,
            static fn(array $r): bool => in_array($collection, $r['collections'], true)
        ));
    }
    if ($scoreOnly) {
        $rows = array_values(array_filter($rows, static fn(array $r): bool => !empty($r['score'])));
    }
    if ($q === '') {
        return $rows;
    }

    $needle = mb_strtolower($q);
    $scored = [];
    foreach ($rows as $r) {
        $rank = hymnal_match_rank($r, $needle);
        if ($rank > 0) {
            $scored[] = ['rank' => $rank, 'row' => $r];
        }
    }
    usort($scored, static function (array $a, array $b): int {
        return $b['rank'] <=> $a['rank']
            ?: strcasecmp($a['row']['title'], $b['row']['title']);
    });

    return array_map(static fn(array $s): array => $s['row'], $scored);
}

/**
 * How well one row matches, higher being better. Exact number beats exact
 * title beats title prefix beats first line beats writer.
 */
function hymnal_match_rank(array $row, string $needle): int
{
    if ($needle === '') {
        return 1;
    }
    if (ctype_digit($needle) && (int) $needle === (int) $row['n']) {
        return 1000;
    }
    $title = mb_strtolower((string) $row['title']);
    $first = mb_strtolower((string) ($row['first_line'] ?? ''));
    $writer = mb_strtolower((string) ($row['writer'] ?? ''));

    if ($title === $needle) {
        return 900;
    }
    if (str_starts_with($title, $needle)) {
        return 800;
    }
    if (str_starts_with($first, $needle)) {
        return 700;
    }
    if (str_contains($title, $needle)) {
        return 600;
    }
    if (str_contains($first, $needle)) {
        return 500;
    }
    if (str_contains($writer, $needle)) {
        return 300;
    }
    foreach ($row['themes'] ?? [] as $t) {
        if (str_contains(mb_strtolower((string) $t), $needle)) {
            return 200;
        }
    }

    return 0;
}

/**
 * Check every corpus file against MANIFEST.
 *
 * This is the guarantee the whole file-based design rests on, so it is a
 * function rather than a line in the test: tests/hymnal/run.php calls it, and
 * the Studio's health panel can too.
 *
 * @return array{ok:bool, checked:int, problems:list<string>}
 */
function hymnal_corpus_verify(): array
{
    $dir = hymnal_corpus_dir();
    $manifest = $dir . '/MANIFEST';
    if (!is_file($manifest)) {
        return ['ok' => false, 'checked' => 0, 'problems' => ['MANIFEST is missing']];
    }
    $problems = [];
    $checked = 0;
    $listed = [];
    foreach (file($manifest, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [] as $line) {
        if ($line === '' || $line[0] === '#') {
            continue;
        }
        $parts = preg_split('/\s+/', trim($line), 2);
        if (count($parts) !== 2) {
            $problems[] = 'MANIFEST line is malformed: ' . $line;
            continue;
        }
        [$want, $name] = $parts;
        $listed[$name] = true;
        $path = $dir . '/' . $name;
        if (!is_file($path)) {
            $problems[] = "$name is listed in MANIFEST but missing";
            continue;
        }
        $checked++;
        $got = hash_file('sha256', $path);
        if (!hash_equals($want, (string) $got)) {
            $problems[] = "$name does not match MANIFEST (expected $want, got $got)";
        }
    }
    // A generated file nobody pinned is as much of a problem as a changed one.
    foreach (glob($dir . '/*.php') ?: [] as $path) {
        $name = basename($path);
        if (!isset($listed[$name])) {
            $problems[] = "$name is in the corpus but not listed in MANIFEST";
        }
    }

    return ['ok' => $problems === [], 'checked' => $checked, 'problems' => $problems];
}
